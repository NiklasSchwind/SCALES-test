"""
annual_ssm_dit
==============

Annual-SSM-conditioned outpainting diffusion transformer for regional tas/pr.

Relation to `ssm_dit`
---------------------
`ssm_dit` carried two latent processes behind one interface: the monthly
`DeepSSMPatternConditioned` and the `AnnualSSM`. This module keeps only the
annual path — no import of `scales_ssm_cross_corr_osc_trans`, no ACF term, no
`ctrl_lin` ridge — and changes the two things that made that path behave unlike
a state space model:

1. **z is state again.** It is rolled forward *once* across the whole projection
   and each DiT block reads a slice of that single trajectory.
   `ssm_dit.sample_blocks` re-derived z from the trailing `context_len` window at
   every block, so no latent state survived a block boundary and nothing could
   carry information further back than the context window. Here the transition
   is iterated over the full horizon, so the forced response accumulates
   `B(u_t)` along the entire pathway.

2. **The transition has no oscillator.** Autocorrelation, including the ENSO
   band, is the DiT's job now.

Division of labour
------------------
    z               causal forced-response state: a bank of learned leaky
                    integrators of GSAT, carried across every block
    memory kernels  short-range (<= 20 yr) memory, window-local by design
    month embedding the seasonal cycle
    DiT             everything local, *including* temporal autocorrelation and
                    the ENSO band, which used to be the oscillator's job

Why the oscillator is gone
--------------------------
The damped 2-D rotation existed to put oscillatory structure in z's ACF, and it
only ever earned its amplitude from an ACF loss that the annual model does not
have. The replacement is a per-dimension contraction, `z <- d * z + B(u)` with
`d = sigmoid(.) in (0, 1)`: every eigenvalue is real and inside the unit circle,
so a 140-step rollout is stable by construction and cannot ring. A general dense
`A` is deliberately *not* offered — its eigenvalues are complex in general,
which would smuggle the oscillator back in through the back door.

At initialisation the decays are spread over e-folding times of 1..50 years, so
z starts life as a multi-timescale causal filter bank on the forcing. That is
the same idea as the memory kernels, but stateful and learned, which is what
lets it outlive a block.

Why the conditioning z is the mean, not a sample
------------------------------------------------
With state-independent process noise, a *sampled* rollout approaches its
stationary distribution after a few e-folding times, so blocks deep in the
horizon would be conditioned on a z whose informative content is swamped by
accumulated noise — and the DiT's rational response to that is to learn to
ignore z. Because the transition is linear-Gaussian, mean propagation
`mu <- d * mu + B(u)` is the *exact* conditional mean, not an approximation, so
conditioning on it costs nothing and keeps z a clean forced-response signal.
Internal variability is generated by the diffusion process instead. (A
non-zero `trans_hidden` breaks the exactness — see `roll_forward`.)

Why the forcing memory stays window-local
-----------------------------------------
`mem_u` could be computed over the entire known GSAT path at no leakage cost,
since forcing is known ahead of time. It deliberately is not: a conditioner that
sees the global shape of the trajectory keys on that shape and fails to transfer
to pathways outside the training set, which is the failure this architecture
exists to avoid. Long-range forcing information reaches the DiT only through z,
which is causal by construction.

Known limitation (deferred)
---------------------------
Training is teacher-forced in the *field*: every block's local context is
ground truth, while at sampling time every block after the first sees its own
output. Fixing the z mismatch does not fix that one. If long projections still
drift, compare per-block sample statistics at block 0 against the last block
before blaming z.

Conventions
-----------
The field is `x = cat([tas, pr], dim=-1)`, `2 * y_dim` channels, in normalised
units. One `transition` call is one year (dt = 1 is implicit; the only thing
tying the latent clock to physical time is `to_annual`), so `context_len` and
`block_len` must both be whole years for block boundaries to land on annual
boundaries.
"""

